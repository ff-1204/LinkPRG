export const HELP_HEAD = '## ';
/** 겪은 것에 따라 생기는 줄들 앞에 붙는 작은 제목. */
export const MORE_HEAD = '## 다녀온 곳에서 알게 된 것';
/** 그 갈래의 문단들: 늘 보이는 것 뒤에, 겪은 것(seen)에 따라 생기는 줄을 잇는다. */
export function helpBody(topic, seen = {}) {
  const more = (HELP_MORE[topic.id] || []).filter((x) => seen[x.needs]).map((x) => x.text);
  return [...topic.body, ...(more.length ? [MORE_HEAD] : []), ...more];
}
