export const TENT_CHAPTERS = [6, 7, 8, 9, 10, 11, 12];
/** 그 장을 푼 길: 이번 삶에 푼 길이 먼저고, 없으면 지난 삶에 푼 길이다 (CM-G4). */
export function pathOf(state, chapter) {
  const now = [...(state.main?.done || [])].reverse().find((d) => d && d.chapter === chapter);
  const past = (state.main?.past || []).find((d) => d && d.chapter === chapter);
  return (now || past)?.path || null;
}
/** 그 장을 어느 쪽으로 풀었나: 'force' | 'hand' | 'word' | null(1부의 숨은 길처럼 셋에 들지 않는 길). */
export const kindOf = (state, chapter) => PATH_KIND[chapter]?.[pathOf(state, chapter)] || null;
/** 일곱 장을 쪽마다 센다. */
export function kindCount(state) {
  const out = { force: 0, hand: 0, word: 0 };
  for (const ch of TENT_CHAPTERS) { const k = kindOf(state, ch); if (k) out[k] += 1; }
  return out;
}

